let sprache = "en";

// Der Portier: holt einen Text in der aktuellen Sprache und füllt Platzhalter
function t(schluessel, werte) {
    let text = (TEXTE[sprache] && TEXTE[sprache][schluessel]) || TEXTE.en[schluessel] || schluessel;
    if (werte) {
        Object.keys(werte).forEach(function (platzhalter) {
            text = text.split("{" + platzhalter + "}").join(werte[platzhalter]);
        });
    }
    return text;
}

// Zahlen und Datum im Format der Sprache: 1,842 (EN) oder 1.842 (DE)
function gebietsschema() {
    return sprache === "de" ? "de-DE" : "en-US";
}

// Übersetzt alle festen Texte im HTML. Elemente sagen per Attribut, was sie brauchen:
// data-t (Text), data-t-ph (Platzhalter), data-t-aria (Vorlesetext), data-t-title, data-t-html
function texteAnwenden() {
    document.documentElement.lang = sprache;
    document.querySelectorAll("[data-t]").forEach(function (el) { el.textContent = t(el.dataset.t); });
    document.querySelectorAll("[data-t-ph]").forEach(function (el) { el.placeholder = t(el.dataset.tPh); });
    document.querySelectorAll("[data-t-aria]").forEach(function (el) { el.setAttribute("aria-label", t(el.dataset.tAria)); });
    document.querySelectorAll("[data-t-title]").forEach(function (el) { el.title = t(el.dataset.tTitle); });
    // Nur für unsere eigenen, festen Texte (nie für Eingaben von Nutzern)
    document.querySelectorAll("[data-t-html]").forEach(function (el) { el.innerHTML = t(el.dataset.tHtml); });
}
